"""
Zoho Flow CRM Integration Service.

Transmits structured post-call summaries and lead details to the Zoho Flow
incoming webhook URL asynchronously, without blocking or impacting real-time
telephony or Gemini audio streaming.
"""

import json
import logging
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional
import httpx

from backend.app.settings import settings

logger = logging.getLogger(__name__)


def format_transcript_as_text(transcript_history: Optional[List[Dict[str, Any]]]) -> str:
    """Formats raw conversational turn history into clean human-readable dialogue."""
    if not transcript_history:
        return ""
    lines = []
    for turn in transcript_history:
        role = "Caller" if turn.get("role") == "user" else "Kiara (AI Assistant)"
        text = (turn.get("content") or turn.get("text", "")).strip()
        if text:
            lines.append(f"{role}: {text}")
    return "\n\n".join(lines)


async def send_call_summary_to_zoho(
    call_id: str,
    user_info: Dict[str, Any],
    summary: Dict[str, Any],
    transcript_history: Optional[List[Dict[str, Any]]] = None,
    lead_id: Optional[str] = None,
    booking_lead_id: Optional[str] = None,
    include_transcript: bool = False,
    call_duration_seconds: Optional[int] = None,
) -> bool:
    """
    Sends structured lead and clinical call summary to Zoho Flow incoming webhook.

    Parameters:
        call_id: Unique call session identifier.
        user_info: Caller details captured during or before the call (name, phone, city, etc.).
        summary: Structured summary dictionary generated by Gemini (CallSummarySchema).
        transcript_history: Optional turn history.
        lead_id: Optional existing lead identifier.
        include_transcript: If True, attaches formatted transcript text.
        call_duration_seconds: Optional call duration in seconds.

    Returns:
        bool: True if Zoho Flow returned HTTP 200/201/202, False otherwise.
    """
    webhook_url = settings.ZOHO_FLOW_WEBHOOK_URL
    if not webhook_url:
        logger.warning("[Zoho Flow] No webhook URL configured (ZOHO_FLOW_WEBHOOK_URL is empty). Skipping dispatch.")
        return False

    if not summary:
        logger.info(f"[Zoho Flow] Skipping call {call_id}: No summary available.")
        return False

    concerns_raw = summary.get("key_concerns") or []
    concerns_text = ", ".join(concerns_raw) if isinstance(concerns_raw, list) else str(concerns_raw)

    actions_raw = summary.get("next_actions") or []
    actions_text = "\n".join(f"- {a}" for a in actions_raw) if isinstance(actions_raw, list) else str(actions_raw)

    lead_name = user_info.get("name") or ""
    lead_phone = user_info.get("phone") or ""
    lead_email = user_info.get("email") or ""
    lead_city = user_info.get("city") or ""
    lead_pincode = user_info.get("pincode") or ""

    call_outcome = summary.get("call_outcome") or "information_provided"
    callback_time = summary.get("callback_time") or ""

    # Structured payload supporting both flat top-level mapping and nested structures
    payload: Dict[str, Any] = {
        "event": "call_completed",
        "timestamp": datetime.now(timezone.utc).isoformat(),
        "call_id": call_id,
        "lead_id": lead_id or user_info.get("lead_id") or "",
        "booking_lead_id": booking_lead_id or user_info.get("booking_lead_id") or summary.get("booking_lead_id") or "",
        # Flat fields for instant drag-and-drop mapping in Zoho Flow UI
        "name": lead_name,
        "phone": lead_phone,
        "email": lead_email,
        "city": lead_city,
        "pincode": lead_pincode,
        "summary": summary.get("summary") or "",
        "key_concerns": concerns_text,
        "call_outcome": call_outcome,
        "callback_time": callback_time,
        "booking_status": summary.get("booking_status") or "not_discussed",
        "customer_sentiment": summary.get("customer_sentiment") or "neutral",
        "language_used": summary.get("language_used") or "English",
        "next_actions": actions_text,
        # Grouped objects for advanced Zoho Flow triggers
        "lead_details": {
            "name": lead_name,
            "phone": lead_phone,
            "email": lead_email,
            "city": lead_city,
            "pincode": lead_pincode,
            "lead_id": lead_id or user_info.get("lead_id") or "",
            "booking_lead_id": booking_lead_id or user_info.get("booking_lead_id") or summary.get("booking_lead_id") or "",
            "intent": user_info.get("intent") or "",
            "notes": user_info.get("notes") or "",
        },
        "summary_details": {
            "overview": summary.get("summary") or "",
            "key_concerns": concerns_raw if isinstance(concerns_raw, list) else [concerns_text],
            "concerns_text": concerns_text,
            "call_outcome": call_outcome,
            "callback_time": callback_time,
            "booking_status": summary.get("booking_status") or "not_discussed",
            "customer_sentiment": summary.get("customer_sentiment") or "neutral",
            "language_used": summary.get("language_used") or "English",
            "next_actions": actions_raw if isinstance(actions_raw, list) else [actions_text],
            "next_actions_text": actions_text,
        },
    }

    if call_duration_seconds is not None:
        payload["call_duration_seconds"] = call_duration_seconds

    if include_transcript and transcript_history:
        payload["transcript_text"] = format_transcript_as_text(transcript_history)
        payload["turn_count"] = len(transcript_history)

    try:
        logger.info(f"[Zoho Flow] Dispatching call summary for {call_id} to Zoho Flow...")
        async with httpx.AsyncClient(timeout=10.0) as client:
            response = await client.post(
                webhook_url,
                json=payload,
                headers={"Content-Type": "application/json"},
            )
            if response.status_code in (200, 201, 202):
                logger.info(
                    f"[Zoho Flow] Successfully delivered summary for call {call_id} (HTTP {response.status_code})"
                )
                print(f"[Zoho Flow] [SUCCESS] Webhook delivered for call {call_id} (HTTP {response.status_code})")
                return True
            else:
                logger.warning(
                    f"[Zoho Flow] Webhook returned non-success HTTP {response.status_code} for call {call_id}: {response.text}"
                )
                print(f"[Zoho Flow] [WARNING] Webhook returned HTTP {response.status_code}: {response.text[:200]}")
                return False
    except httpx.TimeoutException:
        logger.error(f"[Zoho Flow] Request timed out after 10s for call {call_id}")
        print(f"[Zoho Flow] [TIMEOUT] Webhook timed out after 10s for call {call_id}")
        return False
    except Exception as e:
        logger.error(f"[Zoho Flow] Error sending call summary to Zoho Flow for call {call_id}: {e}", exc_info=True)
        print(f"[Zoho Flow] [ERROR] Webhook error for call {call_id}: {e}")
        return False
